from typing import Any


def argument_match_score(
    expected: dict[str, Any],
    actual: dict[str, Any],
) -> float:
    """
    Compare only arguments explicitly required
    by the evaluation case.

    Extra arguments generated by the model
    are not penalized.
    """

    if not expected:
        return 1.0

    matched = 0

    for key, expected_value in (
        expected.items()
    ):

        if key not in actual:
            continue

        actual_value = actual[key]

        if str(actual_value) == str(
            expected_value
        ):
            matched += 1

    return matched / len(
        expected
    )